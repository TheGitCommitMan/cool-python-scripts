# Defining our variables
n=0 # This tells python that n is defined as 0
userInput=int(input("How many times do you want to print it? "))
userPhrase=input("Enter a phrase: ") # tells python to ask the user to input a phrase

# Repeats the phrase the requested amount of times
while n <userInput: # a while loop
    print(userPhrase)
    n+= 1 # increments it
    
print("execution complete XD")
    
    
    
    
    
    
    
    
